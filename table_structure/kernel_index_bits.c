// kernel_index_bits.c — 索引ビット特定用カーネル【未実装・設計メモ】
//
// 注意: aliasing の掃引実験（table_bench --mode alias）とは別物である。
// alias モードは分岐サイト数を増やして衝突の可能性を高める実験であり、
// こちらは「索引にアドレスのどのビットが使われているか」を特定するもの。
//
// 目的:
//   予測テーブルの索引に分岐アドレスのどのビットが使われているかを特定する。
//   二つの分岐サイトのアドレスを制御し、下位ビットの整合を段階的に上げていくと、
//   索引に使われるビットが一致した時点で両者が同一エントリを共有し(エイリアシング)、
//   互いに矛盾する結果を学習させると予測精度が崩れる。崩れ始める整合ビット数から、
//   索引に使われるビット範囲が定まる。
//
// 実装方針(要検討):
//   C の関数配置ではアドレスのビット単位の制御が難しい。候補は二つ。
//   (a) mmap(MAP_FIXED) で任意アドレスに実行可能領域を確保し、小さな
//       条件分岐ループの機械語を書き込む。アドレスを完全に制御できるが
//       アーキテクチャ依存になる。
//   (b) リンカスクリプトまたは asm の .balign で、既知のアドレス差を持つ
//       スタブ対を配置する。移植性は高いが差の細かい制御が難しい。
//
// 現状: dual / ctx / alias 観測を先に固めるため未実装。
//       着手時に (a) を試し、対象アーキテクチャで機械語テンプレートを用意する。
